import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const rpc=readFileSync('supabase/migrations/20261023220500_afat_atomic_pending_incident_review.sql','utf8');
const api=readFileSync('src/api/routes.ts','utf8');
const ui=readFileSync('dashboard/src/components/admin/EvidenceReviewQueue.tsx','utf8');
const start=api.indexOf("router.get('/ops/incidents/review-queue'");
const end=api.indexOf("router.post('/ops/map-signal-reviews'",start);
assert.ok(start>0&&end>start,'Existing staff authority intake must expose a review queue and decision API');
const section=api.slice(start,end);
assert.ok(section.includes("requireAuthRole(req,res,['admin','planner'])"),'Staff authorization must be enforced for both actions');
assert.ok(section.includes("supabase.rpc('afat_decide_pending_incident'"),'Only the atomic RPC transitions evidence');
assert.ok(rpc.includes('for update'),'Decision locks incident against conflicting review');
assert.ok(rpc.includes("coalesce(auth.role(),'')<>'service_role'"),'Direct browser RPC must not authorize itself');
assert.ok(rpc.includes("'INCIDENT_NOT_PENDING'"),'Cannot redo an accepted staff decision');
assert.ok(rpc.includes("'INCIDENT_ALREADY_EXPIRED'"),'Cannot verify expired threats');
assert.ok(rpc.includes("create table if not exists public.afat_incident_review_events"),'Persist review evidence');
assert.ok(rpc.includes("verification_status=case when p_decision='verify' then 'verified' else 'rejected' end"),'Rejects do not promote Atlas truth');
assert.ok(ui.includes('decidePendingIncident')&&ui.includes('incidentNotes'),'Actual evidence review is connected to existing operations UI');
console.log('PASS AFAT reviewed incident worklist, authorization, atomic state, expiry and audit linkage');
